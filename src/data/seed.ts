export function computeAnalytics(products: Product[], orders: Order[]): AnalyticsSummary {
  const validOrders = orders.filter((o) => o.status !== 'cancelado');
  const todayStr = new Date().toISOString().slice(0, 10);
  const todayOrders = validOrders.filter((o) => o.createdAt.startsWith(todayStr));
  const totalRevenue = validOrders.reduce((acc, o) => acc + o.total, 0);
  const todayRevenue = todayOrders.reduce((acc, o) => acc + o.total, 0);
  const pendingOrders = orders.filter(
    (o) => o.status === 'novo' || o.status === 'separacao' || o.status === 'entrega'
  ).length;
  const lowStockCount = products.filter((p) => p.active && p.stock <= 5).length;
  const activeOffersCount = products.filter((p) => p.active && p.isDailyOffer).length;
  const flyerItemsCount = products.filter((p) => p.active && p.inDigitalFlyer).length;

  return {
    totalRevenue,
    todayRevenue,
    totalOrders: validOrders.length,
    pendingOrders,
    averageTicket: validOrders.length > 0 ? totalRevenue / validOrders.length : 0,
    lowStockCount,
    activeOffersCount,
    flyerItemsCount,
  };
}
